def get_existing_external_ids(session, external_ids: list[str]) -> set[str]:
    """Fetch external_ids that already exist in the database."""
    if not external_ids:
        return set()

    # Query in batches to avoid overly large IN clauses
    existing = set()
    batch_size = 500
    for i in range(0, len(external_ids), batch_size):
        batch = external_ids[i : i + batch_size]
        stmt = select(Ad.external_id).where(Ad.external_id.in_(batch))
        rows = session.execute(stmt).scalars().all()
        existing.update(r for r in rows if r is not None)

    return existing


def insert_ads(session, parsed_ads: list[dict], category: AdCategoryEnum) -> tuple[int, int]:
    """Insert parsed ads into the database, skipping duplicates.

    Returns (new_count, duplicate_count).
    """
    if not parsed_ads:
        return 0, 0

    # Pre-fetch existing external_ids for deduplication
    candidate_ids = [a["external_id"] for a in parsed_ads if a.get("external_id")]
    existing_ids = get_existing_external_ids(session, candidate_ids)

    new_count = 0
    dup_count = 0

    for ad_data in parsed_ads:
        ext_id = ad_data.get("external_id")

        # Skip duplicates
        if ext_id and ext_id in existing_ids:
            dup_count += 1
            continue

        ad = Ad(
            external_id=ext_id,
            title=ad_data.get("title"),
            description=ad_data.get("description"),
            platform=ad_data.get("platform", AdPlatformEnum.FACEBOOK),
            status=AdStatusEnum.PENDING,
            category=category,
            creative_type="unknown",
            advertiser_name=ad_data.get("advertiser_name"),
            snapshot_url=ad_data.get("snapshot_url"),
            first_seen_at=ad_data.get("first_seen_at"),
            last_seen_at=ad_data.get("last_seen_at"),
            ad_metadata=ad_data.get("ad_metadata", {}),
        )
        session.add(ad)
        new_count += 1

        # Track inserted id to avoid intra-batch duplicates
        if ext_id:
            existing_ids.add(ext_id)

    session.commit()
    return new_count, dup_count


