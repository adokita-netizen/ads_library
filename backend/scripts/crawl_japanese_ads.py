def load_keywords() -> list[dict]:
    """Load crawl keywords from the exports/crawl_keywords.json file.

    Expected format (from generate_crawl_keywords.py):
      {
        "keyword_suggestions": [
          { "genre": "skincare", "label": "Skincare", "keywords": [...], "priority": "high" },
          ...
        ]
      }

    Fallback: config/crawl_keywords.json (flat keyword list).

    Returns a list of dicts, each with keys: genre, label, keywords, priority.
    """
    # Try primary path
    for path in [KEYWORDS_PATH, KEYWORDS_SUGGESTION_PATH]:
        if os.path.exists(path):
            try:
                with open(path, "r", encoding="utf-8") as f:
                    data = json.load(f)

                suggestions = data.get("keyword_suggestions")
                if suggestions and isinstance(suggestions, list):
                    print(f"Loaded keyword suggestions from {path}")
                    print(f"  Genres: {len(suggestions)}")
                    return suggestions
            except Exception as e:
                print(f"WARNING: Failed to parse {path}: {e}")

    # Fallback: config/crawl_keywords.json (flat list)
    if os.path.exists(KEYWORDS_CONFIG_PATH):
        try:
            with open(KEYWORDS_CONFIG_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)

            flat_keywords = data.get("keywords", [])
            if flat_keywords:
                print(f"Loaded flat keywords from {KEYWORDS_CONFIG_PATH}")
                print(f"  Keywords: {len(flat_keywords)}")
                # Wrap into a single genre group
                return [{
                    "genre": "general",
                    "label": "General",
                    "keywords": flat_keywords,
                    "priority": "medium",
                }]
        except Exception as e:
            print(f"WARNING: Failed to parse {KEYWORDS_CONFIG_PATH}: {e}")

    print("ERROR: No crawl keywords file found.")
    print(f"  Checked: {KEYWORDS_PATH}")
    print(f"  Checked: {KEYWORDS_SUGGESTION_PATH}")
    print(f"  Checked: {KEYWORDS_CONFIG_PATH}")
    print("  Run generate_crawl_keywords.py first to create the keywords file.")
    return []


