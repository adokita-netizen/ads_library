ESTIMATED_ADS_PER_KEYWORD = 25  # rough estimate for dry-run output


def dry_run(keyword_groups: list[dict]):
    """Print what would be crawled without making API calls."""
    print()
    print("=" * 64)
    print("  DRY RUN MODE (META_ACCESS_TOKEN not set)")
    print("=" * 64)
    print()
    print("  Set the META_ACCESS_TOKEN environment variable to enable")
    print("  actual API calls to the Meta Ad Library.")
    print()

    total_keywords = 0
    total_estimated_ads = 0
    genres_covered = set()

    print(f"  {'Genre':<30s} {'Keywords':>8s} {'Est. Ads':>10s}  Priority")
    print(f"  {'-' * 65}")

    for group in keyword_groups:
        genre = group.get("genre", "unknown")
        label = group.get("label", genre)
        keywords = group.get("keywords", [])
        priority = group.get("priority", "medium")
        kw_count = len(keywords)
        est_ads = kw_count * ESTIMATED_ADS_PER_KEYWORD

        genres_covered.add(genre)
        total_keywords += kw_count
        total_estimated_ads += est_ads

        print(f"  {label:<30s} {kw_count:>8d} {est_ads:>10d}  [{priority}]")

    print()
    print(f"  Total genres:            {len(genres_covered)}")
    print(f"  Total keywords:          {total_keywords}")
    print(f"  Estimated ads (total):   {total_estimated_ads}")
    print()

    # Print sample keywords per genre
    print("  Sample keywords per genre:")
    print(f"  {'-' * 55}")
    for group in keyword_groups:
        genre = group.get("genre", "unknown")
        keywords = group.get("keywords", [])
        if not keywords:
            continue
        print(f"  [{genre}]")
        for kw in keywords[:3]:
            kw_safe = kw.encode("ascii", "replace").decode("ascii")
            print(f"    - {kw_safe}")
        if len(keywords) > 3:
            print(f"    ... and {len(keywords) - 3} more")
        print()

    print(f"Crawled 0 new ads, 0 duplicates skipped, {len(genres_covered)} genres covered")
    print("(Dry run -- no API calls made)")


