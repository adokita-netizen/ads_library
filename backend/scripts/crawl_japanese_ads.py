"""Crawl Japanese ads from Meta Ad Library API.

Reads keywords from exports/crawl_keywords.json (generated by
generate_crawl_keywords.py) and fetches matching ads via the Meta Ad
Library API (v18.0).  New ads are deduplicated by external_id and
inserted into the local SQLite/PostgreSQL database with auto-assigned
category based on the crawl keyword.

If META_ACCESS_TOKEN is not set, performs a DRY RUN that prints what
would be crawled without making actual API calls.

Usage:
    cd C:/Users/ishit/ads_library/backend
    python scripts/crawl_japanese_ads.py
"""

