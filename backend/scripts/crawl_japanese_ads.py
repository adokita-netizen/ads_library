def _guess_category_from_keyword(keyword: str, genre: str | None = None) -> AdCategoryEnum:
    """Map a crawl keyword/genre to an AdCategoryEnum value."""
    # Try genre slug first
    if genre:
        slug = genre.lower().replace(" ", "_")
        if slug in KEYWORD_CATEGORY_MAP:
            return KEYWORD_CATEGORY_MAP[slug]

    # Try exact keyword match against known slugs
    kw_lower = keyword.lower().replace(" ", "_")
    for slug, cat in KEYWORD_CATEGORY_MAP.items():
        if slug in kw_lower:
            return cat

    return AdCategoryEnum.OTHER


