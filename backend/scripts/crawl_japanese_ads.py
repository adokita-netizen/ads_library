def main():
    print("=" * 64)
    print("  Meta Ad Library API Crawler - Japanese Ads")
    print(f"  Executed at: {datetime.now(timezone.utc).isoformat()}")
    print("=" * 64)

    # Load keywords
    keyword_groups = load_keywords()
    if not keyword_groups:
        return

    # Check for access token
    access_token = os.environ.get("META_ACCESS_TOKEN", "").strip()
    if not access_token:
        print()
        print("WARNING: META_ACCESS_TOKEN environment variable is not set.")
        print("Running in DRY RUN mode.")
        dry_run(keyword_groups)
        return

    # Live crawl mode
    today_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    total_new = 0
    total_duplicates = 0
    genres_covered = set()

    print(f"\nAccess token: ...{access_token[-8:]}")
    print(f"API endpoint: {META_API_BASE}")
    print(f"Target country: JP")
    print(f"Keyword groups: {len(keyword_groups)}")
    print()

    for gi, group in enumerate(keyword_groups):
        genre = group.get("genre", "unknown")
        label = group.get("label", genre)
        keywords = group.get("keywords", [])
        priority = group.get("priority", "medium")

        if not keywords:
            print(f"[{gi + 1}/{len(keyword_groups)}] {label} -- no keywords, skipping")
            continue

        genres_covered.add(genre)
        category = _guess_category_from_keyword("", genre)

        print(f"[{gi + 1}/{len(keyword_groups)}] Genre: {label} ({len(keywords)} keywords, priority={priority})")
        print("-" * 50)

        genre_new = 0
        genre_dup = 0

        for ki, keyword in enumerate(keywords):
            kw_safe = keyword.encode("ascii", "replace").decode("ascii")
            print(f"  [{ki + 1}/{len(keywords)}] Keyword: {kw_safe} ...", end=" ", flush=True)

            try:
                raw_ads = fetch_ads_from_meta(access_token, keyword, limit=50)
                print(f"fetched {len(raw_ads)}", end=" ", flush=True)
            except Exception as e:
                print(f"ERROR: {str(e)[:60]}")
                continue

            if not raw_ads:
                print("-> 0 results")
                continue

            # Parse ads
            parsed = []
            for raw in raw_ads:
                parsed_ad = parse_meta_ad(raw, keyword, genre, today_str)
                if parsed_ad.get("external_id"):
                    parsed.append(parsed_ad)

            # Insert into DB
            session = SyncSessionLocal()
            try:
                new_count, dup_count = insert_ads(session, parsed, category)
                genre_new += new_count
                genre_dup += dup_count
                print(f"-> {new_count} new, {dup_count} duplicates")
            except Exception as db_err:
                session.rollback()
                print(f"DB error: {db_err}")
            finally:
                session.close()

            # Polite delay between API calls
            if ki < len(keywords) - 1:
                time.sleep(REQUEST_DELAY_SECONDS)

        total_new += genre_new
        total_duplicates += genre_dup
        print(f"  Genre subtotal: {genre_new} new, {genre_dup} duplicates")
        print()

    # Final summary
    print("=" * 64)
    print("  CRAWL COMPLETE")
    print("=" * 64)
    print()
    print(f"Crawled {total_new} new ads, {total_duplicates} duplicates skipped, {len(genres_covered)} genres covered")
    print()

    # DB stats
    session = SyncSessionLocal()
    try:
        total_ads = session.query(Ad).count()
        api_crawl_count = 0
        all_ads = session.query(Ad).all()
        for ad in all_ads:
            if (ad.ad_metadata or {}).get("source") == "api_crawl":
                api_crawl_count += 1
        print(f"  DB total ads:       {total_ads}")
        print(f"  API-crawled ads:    {api_crawl_count}")
    except Exception as e:
        print(f"  DB stats error: {e}")
    finally:
        session.close()


if __name__ == "__main__":
    main()
