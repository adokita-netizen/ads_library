def fetch_ads_from_meta(access_token: str, keyword: str, limit: int = 50) -> list[dict]:
    """Fetch ads from Meta Ad Library API for a single keyword.

    Returns a list of raw ad dicts from the API response.
    """
    params = {
        "access_token": access_token,
        "search_terms": keyword,
        "ad_reached_countries": "JP",
        "ad_type": "ALL",
        "fields": META_API_FIELDS,
        "limit": min(limit, 100),  # API max per page
    }

    all_ads: list[dict] = []
    url = META_API_BASE

    while url and len(all_ads) < limit:
        try:
            resp = http_requests.get(url, params=params, timeout=30)
            resp.raise_for_status()
            data = resp.json()
        except http_requests.exceptions.HTTPError as e:
            status = e.response.status_code if e.response is not None else "?"
            print(f"API error (HTTP {status}): {e}")
            break
        except http_requests.exceptions.RequestException as e:
            print(f"Request error: {e}")
            break
        except ValueError:
            print("ERROR: Invalid JSON response from Meta API")
            break

        ads_page = data.get("data", [])
        all_ads.extend(ads_page)

        # Pagination
        paging = data.get("paging", {})
        next_url = paging.get("next")
        if next_url and len(all_ads) < limit:
            url = next_url
            params = {}  # next URL contains all params
            time.sleep(REQUEST_DELAY_SECONDS)
        else:
            break

    return all_ads[:limit]


def parse_meta_ad(raw_ad: dict, keyword: str, genre: str, today_str: str) -> dict:
    """Parse a raw Meta API ad response into a dict suitable for Ad model."""
    ad_id = raw_ad.get("id", "")
    external_id = f"meta_{ad_id}" if ad_id else None

    # Extract text fields
    bodies = raw_ad.get("ad_creative_bodies", [])
    description = bodies[0] if bodies else None

    titles = raw_ad.get("ad_creative_link_titles", [])
    title = titles[0] if titles else None

    page_name = raw_ad.get("page_name")
    snapshot_url = raw_ad.get("ad_snapshot_url")

    # Delivery start time -> first_seen_at
    delivery_start = raw_ad.get("ad_delivery_start_time")
    first_seen_at = None
    if delivery_start:
        try:
            first_seen_at = datetime.fromisoformat(
                delivery_start.replace("Z", "+00:00")
            )
        except (ValueError, AttributeError):
            pass

    # Publisher platforms -> determine platform enum
    publisher_platforms = raw_ad.get("publisher_platforms", [])
    if "instagram" in publisher_platforms:
        platform = AdPlatformEnum.INSTAGRAM
    elif "facebook" in publisher_platforms:
        platform = AdPlatformEnum.FACEBOOK
    else:
        platform = AdPlatformEnum.FACEBOOK  # default for Meta API

    return {
        "external_id": external_id,
        "title": title,
        "description": description,
        "platform": platform,
        "advertiser_name": page_name,
        "snapshot_url": snapshot_url,
        "first_seen_at": first_seen_at,
        "last_seen_at": datetime.now(timezone.utc),
        "ad_metadata": {
            "source": "api_crawl",
            "crawl_keyword": keyword,
            "crawl_date": today_str,
            "fine_genre_en": genre,
            "publisher_platforms": publisher_platforms,
            "meta_ad_id": ad_id,
        },
    }


